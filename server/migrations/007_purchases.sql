-- Factures d'achat (kind = invoice) et avoirs fournisseur (kind = credit_note)
CREATE TABLE purchase_invoices (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id          CHAR(36)     NOT NULL,
  company_id         BIGINT UNSIGNED NOT NULL,
  kind               ENUM('invoice','credit_note') NOT NULL DEFAULT 'invoice',
  number             VARCHAR(40)  NULL COMMENT 'numero interne attribue a l''enregistrement',
  series             VARCHAR(20)  NULL,
  status             ENUM('draft','recorded','cancelled') NOT NULL DEFAULT 'draft',
  supplier_ref       VARCHAR(60)  NOT NULL COMMENT 'n° de la facture / de l''avoir chez le fournisseur',
  supplier_id        BIGINT UNSIGNED NOT NULL,
  supplier_snapshot  JSON NOT NULL,
  company_snapshot   JSON NULL,
  order_id           BIGINT UNSIGNED NULL,
  receipt_id         BIGINT UNSIGNED NULL,
  credited_invoice_id BIGINT UNSIGNED NULL,
  credit_reason      VARCHAR(255) NULL,
  issue_date         DATE NOT NULL COMMENT 'date figurant sur le document du fournisseur',
  due_date           DATE NOT NULL,
  currency           CHAR(3)      NOT NULL DEFAULT 'TND',
  exchange_rate      DECIMAL(15,6) NOT NULL DEFAULT 1,
  rate_date          DATE NULL,
  global_discount_pct DECIMAL(5,2) NOT NULL DEFAULT 0,
  subtotal           DECIMAL(15,3) NOT NULL DEFAULT 0,
  line_discount_total DECIMAL(15,3) NOT NULL DEFAULT 0,
  global_discount_amount DECIMAL(15,3) NOT NULL DEFAULT 0,
  total_ht           DECIMAL(15,3) NOT NULL DEFAULT 0,
  total_tax          DECIMAL(15,3) NOT NULL DEFAULT 0,
  total_ttc          DECIMAL(15,3) NOT NULL DEFAULT 0,
  stamp_duty         DECIMAL(15,3) NOT NULL DEFAULT 0,
  withholding_rate   DECIMAL(5,2) NOT NULL DEFAULT 0,
  withholding_amount DECIMAL(15,3) NOT NULL DEFAULT 0,
  net_payable        DECIMAL(15,3) NOT NULL DEFAULT 0,
  payment_terms_days SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  notes              TEXT NULL,
  terms              TEXT NULL,
  paid_amount        DECIMAL(15,3) NOT NULL DEFAULT 0 COMMENT 'recalcule depuis les affectations de reglements',
  cancel_reason      VARCHAR(255) NULL,
  recorded_at        TIMESTAMP NULL,
  recorded_by        BIGINT UNSIGNED NULL,
  cancelled_at       TIMESTAMP NULL,
  created_by         BIGINT UNSIGNED NULL,
  created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_pi_public (public_id),
  UNIQUE KEY uq_pi_number (company_id, number),
  KEY idx_pi_supplier (company_id, supplier_id),
  KEY idx_pi_ref (company_id, supplier_id, kind, supplier_ref),
  KEY idx_pi_due (company_id, due_date),
  KEY idx_pi_order (order_id),
  UNIQUE KEY uq_pi_receipt (receipt_id),
  CONSTRAINT fk_pi_company FOREIGN KEY (company_id) REFERENCES companies (id),
  CONSTRAINT fk_pi_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
  CONSTRAINT fk_pi_order FOREIGN KEY (order_id) REFERENCES purchase_orders (id),
  CONSTRAINT fk_pi_receipt FOREIGN KEY (receipt_id) REFERENCES purchase_receipts (id),
  CONSTRAINT fk_pi_credited FOREIGN KEY (credited_invoice_id) REFERENCES purchase_invoices (id),
  CONSTRAINT fk_pi_user FOREIGN KEY (created_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

