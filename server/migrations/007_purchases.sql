-- 007 : achats (Phase 7B/7C) - commandes fournisseur, receptions (entree en stock), factures d'achat et avoirs fournisseur, reglements fournisseurs

CREATE TABLE purchase_orders (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id          CHAR(36)     NOT NULL,
  company_id         BIGINT UNSIGNED NOT NULL,
  number             VARCHAR(40)  NOT NULL,
  status             ENUM('draft','confirmed','cancelled') NOT NULL DEFAULT 'draft' COMMENT 'reception / facturation = derivees',
  expected_date      DATE NULL,
  cancel_reason      VARCHAR(255) NULL,
  supplier_id        BIGINT UNSIGNED NOT NULL,
  supplier_snapshot  JSON NOT NULL,
  company_snapshot   JSON NULL,
  issue_date         DATE NOT NULL,
  currency           CHAR(3)      NOT NULL DEFAULT 'TND',
  exchange_rate      DECIMAL(15,6) NOT NULL DEFAULT 1,
  rate_date          DATE NULL,
  global_discount_pct DECIMAL(5,2) NOT NULL DEFAULT 0,
  subtotal           DECIMAL(15,3) NOT NULL DEFAULT 0,
  line_discount_total DECIMAL(15,3) NOT NULL DEFAULT 0,
  global_discount_amount DECIMAL(15,3) NOT NULL DEFAULT 0,
  total_ht           DECIMAL(15,3) NOT NULL DEFAULT 0,
  total_tax          DECIMAL(15,3) NOT NULL DEFAULT 0,
  total_ttc          DECIMAL(15,3) NOT NULL DEFAULT 0,
  stamp_duty         DECIMAL(15,3) NOT NULL DEFAULT 0,
  withholding_rate   DECIMAL(5,2) NOT NULL DEFAULT 0,
  withholding_amount DECIMAL(15,3) NOT NULL DEFAULT 0,
  net_payable        DECIMAL(15,3) NOT NULL DEFAULT 0,
  payment_terms_days SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  notes              TEXT NULL,
  terms              TEXT NULL,
  created_by         BIGINT UNSIGNED NULL,
  created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_po_public (public_id),
  UNIQUE KEY uq_po_number (company_id, number),
  KEY idx_po_supplier (company_id, supplier_id),
  KEY idx_po_date (company_id, issue_date),
  CONSTRAINT fk_po_company FOREIGN KEY (company_id) REFERENCES companies (id),
  CONSTRAINT fk_po_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
  CONSTRAINT fk_po_user FOREIGN KEY (created_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE purchase_order_lines (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  purchase_order_id BIGINT UNSIGNED NOT NULL,
  position    SMALLINT UNSIGNED NOT NULL,
  product_id  BIGINT UNSIGNED NULL,
  description VARCHAR(500) NOT NULL,
  quantity    DECIMAL(15,4) NOT NULL,
  unit        VARCHAR(20)  NOT NULL DEFAULT 'unité',
  unit_price  DECIMAL(15,3) NOT NULL,
  discount_pct DECIMAL(5,2) NOT NULL DEFAULT 0,
  tax_rate    DECIMAL(5,2) NOT NULL,
  tax_name    VARCHAR(60)  NULL,
  gross_amount DECIMAL(15,3) NOT NULL,
  discount_amount DECIMAL(15,3) NOT NULL,
  net_amount  DECIMAL(15,3) NOT NULL,
  PRIMARY KEY (id),
  KEY idx_purchase_order_lines_parent (purchase_order_id, position),
  CONSTRAINT fk_purchase_order_lines_parent FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders (id) ON DELETE CASCADE,
  CONSTRAINT fk_purchase_order_lines_product FOREIGN KEY (product_id) REFERENCES products (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE purchase_order_tax_lines (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  purchase_order_id BIGINT UNSIGNED NOT NULL,
  tax_rate    DECIMAL(5,2) NOT NULL,
  base        DECIMAL(15,3) NOT NULL,
  amount      DECIMAL(15,3) NOT NULL,
  PRIMARY KEY (id),
  KEY idx_purchase_order_tax_parent (purchase_order_id),
  CONSTRAINT fk_purchase_order_tax_parent FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

