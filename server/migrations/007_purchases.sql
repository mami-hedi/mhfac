-- Reglements fournisseurs : affectes a une ou plusieurs factures d'achat du meme fournisseur ; jamais supprimes, seulement annules
CREATE TABLE supplier_payments (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id     CHAR(36) NOT NULL,
  company_id    BIGINT UNSIGNED NOT NULL,
  number        VARCHAR(40) NOT NULL,
  supplier_id   BIGINT UNSIGNED NOT NULL,
  payment_date  DATE NOT NULL,
  method        ENUM('cash','bank_transfer','cheque','card','bill_of_exchange','other') NOT NULL,
  currency      CHAR(3) NOT NULL DEFAULT 'TND',
  amount        DECIMAL(15,3) NOT NULL,
  reference     VARCHAR(120) NULL,
  notes         VARCHAR(500) NULL,
  status        ENUM('recorded','cancelled') NOT NULL DEFAULT 'recorded',
  cancel_reason VARCHAR(255) NULL,
  cancelled_at  TIMESTAMP NULL,
  created_by    BIGINT UNSIGNED NULL,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_sp_public (public_id),
  UNIQUE KEY uq_sp_number (company_id, number),
  KEY idx_sp_supplier (company_id, supplier_id),
  KEY idx_sp_date (company_id, payment_date),
  CONSTRAINT fk_sp_company FOREIGN KEY (company_id) REFERENCES companies (id),
  CONSTRAINT fk_sp_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
  CONSTRAINT fk_sp_user FOREIGN KEY (created_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE supplier_payment_allocations (
