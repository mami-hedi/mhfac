-- Phase 7B : trésorerie (comptes bancaires et caisses, transactions, chèques et effets). Aucune connexion bancaire : saisie et rapprochement manuels.
CREATE TABLE treasury_accounts (
  id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id       CHAR(36) NOT NULL,
  company_id      BIGINT UNSIGNED NOT NULL,
  code            VARCHAR(20) NOT NULL,
  name            VARCHAR(120) NOT NULL,
  type            ENUM('bank','cash') NOT NULL DEFAULT 'bank',
  currency        CHAR(3) NOT NULL DEFAULT 'TND',
  bank_name       VARCHAR(120) NULL,
  account_number  VARCHAR(40) NULL COMMENT 'RIB / IBAN (informatif)',
  opening_balance DECIMAL(15,3) NOT NULL DEFAULT 0.000,
  opening_date    DATE NOT NULL,
  status          ENUM('active','archived') NOT NULL DEFAULT 'active',
  created_by      BIGINT UNSIGNED NULL,
  created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_tacc_public (public_id),
  UNIQUE KEY uq_tacc_code (company_id, code),
  CONSTRAINT fk_tacc_company FOREIGN KEY (company_id) REFERENCES companies (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE treasury_transactions (
  id             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id      CHAR(36) NOT NULL,
  company_id     BIGINT UNSIGNED NOT NULL,
  number         VARCHAR(40) NOT NULL,
  account_id     BIGINT UNSIGNED NOT NULL,
  tx_date        DATE NOT NULL,
  direction      ENUM('in','out') NOT NULL,
  amount         DECIMAL(15,3) NOT NULL,
  kind           ENUM('client_payment','supplier_payment','instrument','manual','transfer') NOT NULL,
  label          VARCHAR(255) NOT NULL,
  reference      VARCHAR(120) NULL,
  status         ENUM('recorded','cancelled') NOT NULL DEFAULT 'recorded',
  source_type    VARCHAR(30) NULL,
  source_id      CHAR(36) NULL,
  transfer_group CHAR(36) NULL,
  reconciled     TINYINT(1) NOT NULL DEFAULT 0,
  reconciled_at  TIMESTAMP NULL,
  reconciled_by  BIGINT UNSIGNED NULL,
  cancel_reason  VARCHAR(255) NULL,
  cancelled_at   TIMESTAMP NULL,
  created_by     BIGINT UNSIGNED NULL,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_ttx_public (public_id),
  UNIQUE KEY uq_ttx_number (company_id, number),
  UNIQUE KEY uq_ttx_source (company_id, source_type, source_id, direction),
  KEY idx_ttx_account (company_id, account_id, tx_date),
  KEY idx_ttx_group (transfer_group),
  CONSTRAINT fk_ttx_company FOREIGN KEY (company_id) REFERENCES companies (id),
  CONSTRAINT fk_ttx_account FOREIGN KEY (account_id) REFERENCES treasury_accounts (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE treasury_instruments (
  id               BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id        CHAR(36) NOT NULL,
  company_id       BIGINT UNSIGNED NOT NULL,
  direction        ENUM('received','issued') NOT NULL COMMENT 'recu d''un client / emis a un fournisseur',
  type             ENUM('cheque','bill') NOT NULL,
  instrument_number VARCHAR(60) NULL COMMENT 'N° du cheque ou de l''effet',
  bank_name        VARCHAR(120) NULL,
  party_name       VARCHAR(190) NOT NULL,
  amount           DECIMAL(15,3) NOT NULL,
  currency         CHAR(3) NOT NULL DEFAULT 'TND',
  due_date         DATE NULL COMMENT 'echeance',
  status           ENUM('pending','deposited','cleared','bounced','cancelled') NOT NULL DEFAULT 'pending',
  account_id       BIGINT UNSIGNED NULL COMMENT 'compte a crediter / debiter',
  payment_type     ENUM('client_payment','supplier_payment') NOT NULL,
  payment_id       CHAR(36) NOT NULL COMMENT 'public_id du reglement',
  payment_number   VARCHAR(40) NOT NULL,
  deposited_at     DATE NULL,
  cleared_at       DATE NULL,
  bounced_at       DATE NULL,
  note             VARCHAR(255) NULL,
  created_by       BIGINT UNSIGNED NULL,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_tins_public (public_id),
  UNIQUE KEY uq_tins_payment (company_id, payment_type, payment_id),
  KEY idx_tins_status (company_id, status, due_date),
  CONSTRAINT fk_tins_company FOREIGN KEY (company_id) REFERENCES companies (id),
  CONSTRAINT fk_tins_account FOREIGN KEY (account_id) REFERENCES treasury_accounts (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

ALTER TABLE payments ADD COLUMN account_id BIGINT UNSIGNED NULL AFTER method, ADD CONSTRAINT fk_payments_account FOREIGN KEY (account_id) REFERENCES treasury_accounts (id);
ALTER TABLE supplier_payments ADD COLUMN account_id BIGINT UNSIGNED NULL AFTER method, ADD CONSTRAINT fk_spayments_account FOREIGN KEY (account_id) REFERENCES treasury_accounts (id);
