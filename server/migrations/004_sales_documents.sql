-- 004 : documents de vente (Phase 6) : devis, factures et avoirs
-- Montants DECIMAL(15,3), quantites DECIMAL(15,4). Les calculs sont faits par src/core/calc.js (jamais par le client).

CREATE TABLE quotes (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id          CHAR(36)     NOT NULL,
  company_id         BIGINT UNSIGNED NOT NULL,
  number             VARCHAR(40)  NOT NULL,
  status             ENUM('draft','sent','accepted','refused','converted') NOT NULL DEFAULT 'draft' COMMENT 'expire = derive de valid_until',
  valid_until        DATE NOT NULL,
  converted_invoice_id BIGINT UNSIGNED NULL,
  client_id          BIGINT UNSIGNED NOT NULL,
  client_snapshot    JSON NOT NULL COMMENT 'Identite du client au moment de la creation/emission',
  company_snapshot   JSON NULL COMMENT 'Identite de l''entreprise figee a l''emission',
  issue_date         DATE NOT NULL,
  currency           CHAR(3)      NOT NULL DEFAULT 'TND',
  exchange_rate      DECIMAL(15,6) NOT NULL DEFAULT 1 COMMENT 'Taux vers la devise de l''entreprise, fige a l''emission',
  rate_date          DATE NULL,
  global_discount_pct DECIMAL(5,2) NOT NULL DEFAULT 0,
  subtotal           DECIMAL(15,3) NOT NULL DEFAULT 0 COMMENT 'Somme des nets de lignes',
  line_discount_total DECIMAL(15,3) NOT NULL DEFAULT 0,
  global_discount_amount DECIMAL(15,3) NOT NULL DEFAULT 0,
  total_ht           DECIMAL(15,3) NOT NULL DEFAULT 0,
  total_tax          DECIMAL(15,3) NOT NULL DEFAULT 0,
  total_ttc          DECIMAL(15,3) NOT NULL DEFAULT 0,
  stamp_duty         DECIMAL(15,3) NOT NULL DEFAULT 0,
  withholding_rate   DECIMAL(5,2) NOT NULL DEFAULT 0,
  withholding_amount DECIMAL(15,3) NOT NULL DEFAULT 0,
  net_payable        DECIMAL(15,3) NOT NULL DEFAULT 0,
  payment_terms_days SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  notes              TEXT NULL,
  terms              TEXT NULL,
  created_by         BIGINT UNSIGNED NULL,
  created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_quotes_public (public_id),
  UNIQUE KEY uq_quotes_number (company_id, number),
  KEY idx_quotes_client (company_id, client_id),
  KEY idx_quotes_date (company_id, issue_date),
  CONSTRAINT fk_quotes_company FOREIGN KEY (company_id) REFERENCES companies (id),
  CONSTRAINT fk_quotes_client FOREIGN KEY (client_id) REFERENCES clients (id),
  CONSTRAINT fk_quotes_user FOREIGN KEY (created_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE quote_lines (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  quote_id BIGINT UNSIGNED NOT NULL,
  position    SMALLINT UNSIGNED NOT NULL,
  product_id  BIGINT UNSIGNED NULL,
  description VARCHAR(500) NOT NULL,
  quantity    DECIMAL(15,4) NOT NULL,
  unit        VARCHAR(20)  NOT NULL DEFAULT 'unité',
  unit_price  DECIMAL(15,3) NOT NULL,
  discount_pct DECIMAL(5,2) NOT NULL DEFAULT 0,
  tax_rate    DECIMAL(5,2) NOT NULL COMMENT 'Valeur du taux figee a la creation de la ligne',
  tax_name    VARCHAR(60)  NULL,
  gross_amount DECIMAL(15,3) NOT NULL,
  discount_amount DECIMAL(15,3) NOT NULL,
  net_amount  DECIMAL(15,3) NOT NULL,
  
  PRIMARY KEY (id),
  KEY idx_quote_lines_parent (quote_id, position),
  CONSTRAINT fk_quote_lines_parent FOREIGN KEY (quote_id) REFERENCES quotes (id) ON DELETE CASCADE,
  CONSTRAINT fk_quote_lines_product FOREIGN KEY (product_id) REFERENCES products (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE quote_tax_lines (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  quote_id BIGINT UNSIGNED NOT NULL,
  tax_rate    DECIMAL(5,2) NOT NULL,
  base        DECIMAL(15,3) NOT NULL,
  amount      DECIMAL(15,3) NOT NULL,
  PRIMARY KEY (id),
  KEY idx_quote_tax_parent (quote_id),
  CONSTRAINT fk_quote_tax_parent FOREIGN KEY (quote_id) REFERENCES quotes (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE invoices (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id          CHAR(36)     NOT NULL,
  company_id         BIGINT UNSIGNED NOT NULL,
  kind               ENUM('invoice','credit_note') NOT NULL DEFAULT 'invoice',
  number             VARCHAR(40)  NULL COMMENT 'attribue a l''emission',
  series             VARCHAR(20)  NULL COMMENT 'annee de numerotation',
  status             ENUM('draft','issued','cancelled') NOT NULL DEFAULT 'draft' COMMENT 'paye / partiel / en retard = derives de paid_amount et due_date',
  due_date           DATE NOT NULL,
  paid_amount        DECIMAL(15,3) NOT NULL DEFAULT 0 COMMENT 'mis a jour par les paiements (phase 7)',
  quote_id           BIGINT UNSIGNED NULL,
  credited_invoice_id BIGINT UNSIGNED NULL,
  credit_reason      VARCHAR(255) NULL,
  cancel_reason      VARCHAR(255) NULL,
  issued_at          TIMESTAMP NULL,
  issued_by          BIGINT UNSIGNED NULL,
  cancelled_at       TIMESTAMP NULL,
  client_id          BIGINT UNSIGNED NOT NULL,
  client_snapshot    JSON NOT NULL COMMENT 'Identite du client au moment de la creation/emission',
  company_snapshot   JSON NULL COMMENT 'Identite de l''entreprise figee a l''emission',
  issue_date         DATE NOT NULL,
  currency           CHAR(3)      NOT NULL DEFAULT 'TND',
  exchange_rate      DECIMAL(15,6) NOT NULL DEFAULT 1 COMMENT 'Taux vers la devise de l''entreprise, fige a l''emission',
  rate_date          DATE NULL,
  global_discount_pct DECIMAL(5,2) NOT NULL DEFAULT 0,
  subtotal           DECIMAL(15,3) NOT NULL DEFAULT 0 COMMENT 'Somme des nets de lignes',
  line_discount_total DECIMAL(15,3) NOT NULL DEFAULT 0,
  global_discount_amount DECIMAL(15,3) NOT NULL DEFAULT 0,
  total_ht           DECIMAL(15,3) NOT NULL DEFAULT 0,
  total_tax          DECIMAL(15,3) NOT NULL DEFAULT 0,
  total_ttc          DECIMAL(15,3) NOT NULL DEFAULT 0,
  stamp_duty         DECIMAL(15,3) NOT NULL DEFAULT 0,
  withholding_rate   DECIMAL(5,2) NOT NULL DEFAULT 0,
  withholding_amount DECIMAL(15,3) NOT NULL DEFAULT 0,
  net_payable        DECIMAL(15,3) NOT NULL DEFAULT 0,
  payment_terms_days SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  notes              TEXT NULL,
  terms              TEXT NULL,
  created_by         BIGINT UNSIGNED NULL,
  created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_invoices_public (public_id),
  UNIQUE KEY uq_invoices_number (company_id, kind, number),
  KEY idx_invoices_status (company_id, kind, status),
  KEY idx_invoices_quote (quote_id),
  KEY idx_invoices_credited (credited_invoice_id),
  KEY idx_invoices_client (company_id, client_id),
  KEY idx_invoices_date (company_id, issue_date),
  CONSTRAINT fk_invoices_company FOREIGN KEY (company_id) REFERENCES companies (id),
  CONSTRAINT fk_invoices_client FOREIGN KEY (client_id) REFERENCES clients (id),
  CONSTRAINT fk_invoices_user FOREIGN KEY (created_by) REFERENCES users (id),
  CONSTRAINT fk_invoices_quote FOREIGN KEY (quote_id) REFERENCES quotes (id),
  CONSTRAINT fk_invoices_credited FOREIGN KEY (credited_invoice_id) REFERENCES invoices (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

